indicators = ['RSI', 'ATR%', 'EMA_dist%', 'SMA200_dist%', 'BB_pos', 'Vol_ratio', 'Low_wick%']

def col_mean(rows, col):
    vals = [r[col] for r in rows]
    return sum(vals)/len(vals)

symbols = ['AAPL', 'SPY', 'NVDA', 'MSFT']

for i, ind in enumerate(indicators):
    print(f"\n{'='*60}")
    print(f"INDICATOR {i+1}: {ind}")
    print(f"{'='*60}")
    win_higher = 0
    loss_higher = 0
    for sym in symbols:
        wm = col_mean(data[sym]['wins'], i)
        lm = col_mean(data[sym]['losses'], i)
        direction = "W>L" if wm > lm else "L>W"
        if wm > lm:
            win_higher += 1
        else:
            loss_higher += 1
        diff = wm - lm
        print(f"  {sym}: win={wm:.3f}  loss={lm:.3f}  diff={diff:+.3f}  ({direction})")
    consistent = win_higher >= 3 or loss_higher >= 3
    if win_higher >= 3:
        direction_label = "higher_wins"
    elif loss_higher >= 3:
        direction_label = "lower_wins"
    else:
        direction_label = "mixed"
    print(f"  => Consistent: {'Y' if consistent else 'N'} | {win_higher}/4 W>L, {loss_higher}/4 L>W | Direction: {direction_label}")

